def track_names():
    return [n for n, _, _ in TRACK_LIBRARY]


def track_label(name, city, region):
    return f"{name} — {city}, {region}"


def suggest_tracks(query, limit=6):
    q = (query or "").strip().lower()
    if len(q) < 2:
        return []
    starts, contains = [], []
    for name, city, region in TRACK_LIBRARY:
        label = track_label(name, city, region)
        blob = f"{name} {city} {region}".lower()
        if name.lower().startswith(q) or blob.startswith(q):
            starts.append((name, label))
        elif q in blob:
            contains.append((name, label))
        if len(starts) >= limit:
            break
    out = starts + contains
    return out[:limit]


