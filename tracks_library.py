def _norm_track(s):
    import re
    return re.sub(r"[^a-z0-9]+", " ", (s or "").lower()).strip()


SKIP_WORDS = {
    "drag", "dragway", "dragstrip", "strip", "raceway", "park", "motorsports",
    "motorplex", "international", "race", "the", "at", "of", "and",
}


def match_track_from_slip(raw):
    n = _norm_track(raw)
    if not n:
        return None
    exact = []
    loose = []
    for name, city, region in TRACK_LIBRARY:
        nn = _norm_track(name)
        nc = _norm_track(city)
        if n == nn or n == f"{nn} {nc}" or (nc and n == nc):
            exact.append(name)
        elif n in nn or nn in n or (nc and nc in n):
            loose.append(name)
    if exact:
        return exact[0]
    tokens = [t for t in n.split() if t not in SKIP_WORDS and len(t) > 2]
    token_hits = []
    if tokens:
        for name, city, region in TRACK_LIBRARY:
            blob = _norm_track(f"{name} {city} {region}")
            if all(t in blob for t in tokens):
                token_hits.append(name)
        if len(token_hits) == 1:
            return token_hits[0]
    if len(loose) == 1:
        return loose[0]
    if len(token_hits) == 1:
        return token_hits[0]
    return None


def find_track(query):
    matched = match_track_from_slip(query)
    if matched:
        q = matched.lower()
    else:
        q = (query or "").strip().lower()
    if not q:
        return None
    rec = None
    for name, city, region in TRACK_LIBRARY:
        if name.lower() == q:
            rec = {"name": name, "city": city, "region": region, "address": f"{city}, {region}"}
            break
    if rec is None:
        for name, city, region in TRACK_LIBRARY:
            if q in name.lower() or name.lower() in q:
                rec = {"name": name, "city": city, "region": region, "address": f"{city}, {region}"}
                break
    if rec is None:
        return None
    pt = TRACK_POINTS.get(rec["name"].lower())
    if pt:
        rec["lat"], rec["lon"], rec["elev_ft"] = pt
    rec["icao"] = TRACK_ICAO.get(rec["name"].lower())
    return rec


def geocode_track(city, region, cache=None):
    key = f"{city}, {region}".lower()
    if cache is not None and key in cache:
        return cache[key]
    import json
    import urllib.parse
    import urllib.request
    q = urllib.parse.quote(f"{city} {region}")
    url = f"https://geocoding-api.open-meteo.com/v1/search?name={q}&count=1&language=en&format=json"
    lat = lon = None
    try:
        with urllib.request.urlopen(url, timeout=8) as r:
            data = json.loads(r.read().decode())
        res = (data.get("results") or [None])[0] or {}
        lat = res.get("latitude")
        lon = res.get("longitude")
    except Exception:
        pass
    loc = (lat, lon)
    if cache is not None:
        cache[key] = loc
    return loc
